import layoutJson from '../assets/machine/layout.json';

export interface AtlasRect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface KeyLayout {
  name: string;
  /** Centre of the cap, in screen points. */
  x: number;
  y: number;
  row: number;
  /** Where the key's stem hangs: a little off the cap's centre, so that no two stems share a line. */
  stemX: number;
  /** Drawn size of the cap sprite, in screen points. */
  size: number;
  radius: number;
  atlas: AtlasRect;
  /** The cap's face while the figures layer is on (the same face for function keys). */
  figAtlas: AtlasRect;
  /** What the key types in the figures layer; null for function keys. */
  fig: string | null;
}

/**
 * Where every part of the machine goes, in screen points on a 440 x 956 screen.
 * Generated by tools/blender/export_app_assets.py together with the images.
 */
export const layout = layoutJson;

export const keys = layout.keys as KeyLayout[];

/** Hit targets: every key, then the space bar. */
export const SPACE_INDEX = keys.length;
/** The two keys that stay down while their layer is on. */
export const SHIFT_INDEX = keys.findIndex((key) => key.name === 'SHIFT');
export const FIG_INDEX = keys.findIndex((key) => key.name === 'FIG');
export const TARGET_COUNT = keys.length + 1;

/** Characters that fit on one line before the carriage stops. */
export const LINE_CELLS = Math.floor((layout.paper.width - 2 * layout.paper.margin) / layout.cell);

/** Left edge of the paper when `cell` sits under the print point. */
export function paperLeftForCell(cell: number): number {
  'worklet';
  return layout.printX - layout.paper.margin - (cell + 0.5) * layout.cell;
}

/** An A4 sheet is this much taller than it is wide. */
export const SHEET_RATIO = 1.414;
/** Blank paper left under the last line of a sheet that had to be longer than A4. */
const SHEET_FOOT = 60;

/** Full length of the sheet in the machine, in points: A4, or more if more lines were typed. */
export function sheetLength(lines: number): number {
  'worklet';
  return Math.max(layout.paper.width * SHEET_RATIO, layout.paper.topMargin + lines * layout.line + SHEET_FOOT);
}
